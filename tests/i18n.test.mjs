import test from 'node:test';
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { getLanguage, setLanguage, normalizeLanguage, locale, msg, localizedNumber } from '../src/i18n.ts';
import { localizeShell, renderShell } from '../src/shell.ts';

test('language normalization, locale, and plain-text interpolation support English and Korean', t => {
  t.after(() => setLanguage('en'));
  assert.equal(getLanguage(), 'en');
  assert.equal(normalizeLanguage('ko'), 'ko');
  assert.equal(normalizeLanguage('ko-KR'), 'en');
  assert.equal(locale(), 'en-US');
  assert.equal(msg('Hello, {name}: {count}', '안녕, {name}: {count}', { name: 'Team', count: 2 }), 'Hello, Team: 2');
  setLanguage('ko');
  assert.equal(locale(), 'ko-KR');
  assert.equal(msg('Hello, {name}: {count}', '안녕, {name}: {count}', { name: '팀', count: 0 }), '안녕, 팀: 0');
  assert.equal(msg('{unknown} {value}', '{unknown} {value}', { value: '$& <literal>' }), '{unknown} $& <literal>');
  assert.equal(localizedNumber(1234.5), '1,234.5');
});

test('a first office shell is English and offers both explicit language choices', t => {
  const window = new Window();
  t.after(() => { setLanguage('en'); window.close(); });
  setLanguage('en');
  window.document.body.innerHTML = renderShell();
  const document = window.document;
  assert.equal(document.querySelector('#game').getAttribute('aria-label'), 'Cubirumi live office');
  assert.equal(document.querySelector('[data-open="settings"].dock-button').textContent, 'Settings');
  assert.equal(document.querySelector('#setting-language option[value="en"]').textContent, 'English');
  assert.equal(document.querySelector('#setting-language option[value="ko"]').textContent, '한국어');
  assert.equal(document.querySelector('#setting-dormantFloorMinutes option[value="180"]').textContent, '3 hours');
  assert.equal(document.querySelector('#setting-maxFloors option[value="8"]').textContent, '8 floors');
});

test('switching shell copy preserves controls, listeners, focus, live data, and unsaved names', t => {
  const window = new Window();
  t.after(() => { setLanguage('en'); window.close(); });
  setLanguage('en');
  window.document.body.innerHTML = renderShell();
  const document = window.document;
  const company = document.querySelector('#company-name');
  const language = document.querySelector('#setting-language');
  const scene = document.querySelector('#scene');
  const close = document.querySelector('#close-panel');
  const option = document.querySelector('#setting-dormantFloorMinutes option[value="180"]');
  const canvas = document.createElement('canvas');
  scene.append(canvas);
  company.value = 'Unsaved company <이름>';
  company.focus();
  language.value = 'ko';
  document.querySelector('#setting-labels').checked = false;
  document.querySelector('#setting-dormantFloorMinutes').value = '180';
  document.querySelector('#location-project').textContent = '사용자 프로젝트';
  document.querySelector('[data-company-name]').textContent = 'Saved company';
  document.querySelector('[data-owner-name]').textContent = 'Owner name';
  document.querySelector('#dispatch-text').textContent = 'Original event 원문';
  document.querySelector('#active-count').textContent = '13';
  let clicked = 0;
  close.addEventListener('click', () => clicked++);
  setLanguage('ko');
  localizeShell(document);
  assert.equal(document.querySelector('#company-name') === company, true);
  assert.equal(document.querySelector('#close-panel') === close, true);
  assert.equal(document.querySelector('#scene').firstElementChild === canvas, true);
  assert.equal(document.activeElement === company, true);
  assert.equal(company.value, 'Unsaved company <이름>');
  assert.equal(language.value, 'ko');
  assert.equal(document.querySelector('#setting-labels').checked, false);
  assert.equal(document.querySelector('#setting-dormantFloorMinutes').value, '180');
  assert.equal(document.querySelector('#setting-dormantFloorMinutes option[value="180"]') === option, true);
  assert.equal(option.textContent, '3시간');
  assert.equal(document.querySelector('#location-project').textContent, '사용자 프로젝트');
  assert.equal(document.querySelector('[data-company-name]').textContent, 'Saved company');
  assert.equal(document.querySelector('[data-owner-name]').textContent, 'Owner name');
  assert.equal(document.querySelector('#dispatch-text').textContent, 'Original event 원문');
  assert.equal(document.querySelector('#active-count').textContent, '13');
  assert.equal(document.querySelector('#game').getAttribute('aria-label'), 'Cubirumi 실시간 사무실');
  assert.equal(document.querySelector('#zoom-in').getAttribute('title'), '확대 (+)');
  assert.equal(close.getAttribute('aria-label'), '패널 닫기');
  close.click();
  assert.equal(clicked, 1);
  setLanguage('en');
  localizeShell(document);
  assert.equal(document.querySelector('#zoom-in').getAttribute('title'), 'Zoom in (+)');
  assert.equal(close.getAttribute('aria-label'), 'Close panel');
  assert.equal(company.value, 'Unsaved company <이름>');
  assert.equal(document.querySelector('#setting-dormantFloorMinutes').value, '180');
});
